#!/usr/bin/env python3
"""SMTP bulk sender (zero external dependencies, Python standard library only)

Usage:
    python3 scripts/batch_sender.py [max_emails] [input.json] [report_dir]

Input JSON (array):
[
  {
    "brand": "Brand A",
    "contact_person": "Hannah Smith",
    "title": "Buyer",
    "email": "hannah.smith@branda.example",
    "region": "UK",
    "need_tag": "line_a",
    "solution_tag": "compliance",
    "website": "https://branda.example",
    "subject": "Your subject line",
    "body": "e-mail body (if omitted, the built-in minimal generic template is used)"
  }
]

Sending routes (pick one; see references/mail_setup.md):
    A1 single mailbox: SMTP_HOST/SMTP_PORT/SMTP_USER/SMTP_PASS environment variables (generated by mail_setup.py env <provider>)
    A2 hosted multi-mailbox: register with mail_setup.py add → when SMTP_HOST is unset, mailboxes rotate by remaining quota;
       MAILBOX=<id> pins one; volume is capped by the warm-up schedule; a round with bounces above the threshold pauses that mailbox
    B  MCP / connectors: DRY_RUN=1 produces the report → mail_setup.py mcp-export → a human approves each item → the connector drafts/sends

SMTP credentials (all injected via environment variables; no key is hard-coded in the script):
    SMTP_HOST     SMTP server (e.g. smtp.your-mail-provider.com)
    SMTP_PORT     port (default 465, SSL)
    SMTP_USER     login user / sender address
    SMTP_PASS     login password / authorisation code
    SENDER_NAME   sender display name
    SENDER_TITLE  sender job title
    SENDER_WA     WhatsApp number
    SENDER_WEBSITE company website
    SENDER_COMPANY company name
    SEND_INTERVAL seconds between e-mails (default 30)
    DAILY_LIMIT   daily cap (default 200)
    DRY_RUN       set to 1 to preview only, nothing is sent
    UNSUBSCRIBE_URL  optional: one-click unsubscribe HTTPS URL (List-Unsubscribe-Post header is added only when set)
    OPT_OUT_LINE  optional: override the opt-out sentence at the end of the body; profile rules.opt_out_line = "off" disables it
    SEND_WINDOW   recipient-local sending window (default: profile rules.local_send_window, then 09:00-11:00,14:00-16:00)
    SEND_WINDOW_ENFORCE  set 0 to disable the local-time window check (on by default; only applies when a contact has region/tz)

Sending iron rules:
    - run in a single session; no parallel agents
    - generic mailboxes (info@/contact@ etc.) are blocked automatically and never sent to
    - 30-second interval against anti-abuse systems, daily cap 200 e-mails
    - successful sends are written back to sent_history; SMTP rejections are recorded; run imap_scanner 24-48 h later to scan bounces
"""
import json, sys, os, ssl, smtplib, time, subprocess, datetime
import send_window as _sw  # recipient-local sending window
import mail_setup as _ms   # sending route: single mailbox / hosted multi-mailbox warm-up / MCP
from email.mime.text import MIMEText
from email.header import Header
from email.utils import formataddr
for _s in (sys.stdout, sys.stderr):  # keep non-ASCII output safe when redirected or on legacy Windows consoles
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    import config as _cfg
except ImportError:
    _cfg = None

# Generic mailbox prefix blocklist (very high bounce rate; never send cold e-mail to these)
# Industry-agnostic generic/functional prefixes are maintained in config.GENERIC_MAILBOX_PREFIXES
GENERIC_PREFIXES = set(_cfg.GENERIC_MAILBOX_PREFIXES) if _cfg is not None else {
    "info", "contact", "hello", "sales", "support", "admin", "office", "service",
}

# Multilingual greetings (matched by region; English when there is no match)
GREETINGS = {
    "IT": "Buongiorno", "DE": "Guten Tag", "FR": "Bonjour", "ES": "Hola",
    "JP": "こんにちは", "NL": "Goedendag", "PT": "Olá", "BR": "Olá",
}


def is_generic(email):
    local = email.split("@")[0].lower().strip()
    return local in GENERIC_PREFIXES


def env(key, default=""):
    return os.environ.get(key, default)


def first_name(contact, region=""):
    """Greeting name: first name only (\"Hannah Smith\" -> \"Hannah\").

    Honorifics are dropped. For JP the full name is kept, because the local
    convention is surname-based and the draft should be localised by a human.
    """
    contact = (contact or "").strip()
    if not contact:
        return ""
    if (region or "").upper() == "JP":
        return contact
    parts = [t for t in contact.replace(",", " ").split()
             if t.lower().rstrip(".") not in {"mr", "mrs", "ms", "miss", "dr", "prof", "sir", "madam"}]
    return parts[0] if parts else contact


def build_body(item, sender, profile):
    """When no body is given, build a minimal generic body from the company_profile positioning / selling points.

    This script contains no industry-specific wording; every product fact comes from the product.* fields
    the user filled in at install. If the draft already has a body (a human/AI-reviewed localised e-mail), it is used as is.
    """
    if item.get("body"):
        return item["body"]
    region = (item.get("region") or "").upper()
    greeting = GREETINGS.get(region, "Hello")
    contact = first_name(item.get("contact_person"), region) or "there"
    brand = item.get("brand") or "your brand"

    one_liner = (profile.get("product", {}).get("one_liner_en") or "").strip()
    diffs = profile.get("product", {}).get("differentiators") or []

    lines = [f"{greeting} {contact},", ""]
    if one_liner:
        # No "came across" / "may be a fit" — both are on the banned list in
        # references/email_templates.md. State the offer, then the proof.
        lines.append(f"A quick note for the {brand} team: we provide {one_liner.rstrip('.')}.")
        lines.append("")
    for d in diffs[:3]:
        d = str(d).strip()
        if d:
            lines.append(f"- {d}")
    facts = list(_cfg.offer_facts(profile))   # offer.key_facts, compatible with legacy moq/sampling fields
    if facts and sender.get("wa"):
        facts.append(f"WhatsApp: {sender['wa']}")
    if facts:
        lines.append("")
        lines.append(". ".join(facts) + ".")
    lines += ["", _cfg.cta_question(profile), "", "Best,",
              _signature_line(sender, profile)]
    return "\n".join(lines)


def _signature_line(sender, profile):
    parts = [sender.get("name") or profile.get("contact", {}).get("founder_name", "")]
    company = sender.get("company") or profile.get("company", {}).get("brand_display", "")
    if company:
        parts = [(parts[0] + f" | {company}") if parts[0] else company]
    tail = []
    site = sender.get("website") or profile.get("company", {}).get("website", "")
    if site:
        tail.append(site)
    wa = sender.get("wa") or profile.get("contact", {}).get("whatsapp", "")
    if wa:
        tail.append(f"WhatsApp: {wa}")
    if tail:
        parts.append(" | ".join(tail))
    return " | ".join([p for p in parts if p])


DEFAULT_OPT_OUT = "If this isn't relevant for you, just reply \"no\" and I won't write again."


def opt_out_line(profile):
    v = os.environ.get("OPT_OUT_LINE") or (profile.get("rules", {}) or {}).get("opt_out_line") or DEFAULT_OPT_OUT
    return "" if str(v).strip().lower() == "off" else str(v).strip()


def with_opt_out(body, profile):
    """Append an opt-out sentence at the end of the body (not duplicated if already present). What you see in the dry-run report is the final body."""
    line = opt_out_line(profile)
    if not line or line.lower() in body.lower():
        return body
    return body.rstrip() + "\n\n" + line


def compose(subject, body, sender_name, from_addr, to_addr):
    """Plain-text e-mail + unsubscribe headers (mailto; one-click added when UNSUBSCRIBE_URL is set)."""
    msg = MIMEText(body, "plain", "utf-8")
    msg["Subject"] = Header(subject, "utf-8")
    msg["From"] = formataddr((str(Header(sender_name, "utf-8")), from_addr))
    msg["To"] = to_addr
    lu = [f"<mailto:{from_addr}?subject=unsubscribe>"] if from_addr else []
    url = os.environ.get("UNSUBSCRIBE_URL", "").strip()
    if url.startswith("https://"):
        lu.insert(0, f"<{url}>")
        msg["List-Unsubscribe-Post"] = "List-Unsubscribe=One-Click"
    if lu:
        msg["List-Unsubscribe"] = ", ".join(lu)
    return msg


def csv_ops(args, data_dir):
    """Call csv_ops.py in the same directory to write data back."""
    here = os.path.dirname(os.path.abspath(__file__))
    env2 = dict(os.environ)
    if data_dir:
        env2["B2B_DATA_DIR"] = data_dir
    try:
        subprocess.run([sys.executable, os.path.join(here, "csv_ops.py"), *args],
                       env=env2, check=False, capture_output=True)
    except Exception as e:
        print(f"  WARN: csv_ops write-back failed: {e}")


def main():
    if len(sys.argv) > 1 and sys.argv[1] in ("-h", "--help", "help"):
        print(__doc__)
        sys.exit(0)
    if len(sys.argv) > 1:
        try:
            max_send = int(sys.argv[1])
            if max_send <= 0:
                raise ValueError
        except ValueError:
            print(f"ERROR: the first argument must be the maximum number of e-mails (positive integer), got \"{sys.argv[1]}\".\n"
                  "Usage: python3 scripts/batch_sender.py [max_emails] [input.json] [report_dir]\n"
                  "Example: DRY_RUN=1 python3 scripts/batch_sender.py 20 drafts.json reports")
            sys.exit(1)
    else:
        max_send = int(env("DAILY_LIMIT", "200"))
    infile = sys.argv[2] if len(sys.argv) > 2 else "candidates.json"
    report_dir = sys.argv[3] if len(sys.argv) > 3 else "reports"
    data_dir = env("B2B_DATA_DIR", "data")
    dry_run = env("DRY_RUN", "") in ("1", "true", "yes")

    # Install gate: no profile / incomplete profile → refuse to send (DRY_RUN too, to avoid sending empty templates)
    if _cfg is not None:
        try:
            profile = _cfg.load_profile(require_complete=True)
        except _cfg.ProfileNotConfigured as e:
            print("ERROR: company profile not ready; sending is blocked.\n" + str(e))
            sys.exit(2)
    else:
        print("ERROR: config.py install gate not found; sending is blocked.")
        sys.exit(2)

    _co = profile.get("company", {})
    _ct = profile.get("contact", {})
    profile_limit = profile.get("rules", {}).get("daily_limit")
    daily_limit = int(env("DAILY_LIMIT", str(profile_limit or 200)))
    max_send = min(max_send, daily_limit)
    interval = float(env("SEND_INTERVAL", "30"))

    # Environment variables win; fall back to the install profile; leave empty only if both are empty (no invented placeholders)
    sender = {
        "name": env("SENDER_NAME") or _ct.get("founder_name", ""),
        "title": env("SENDER_TITLE") or _ct.get("founder_title", ""),
        "wa": env("SENDER_WA") or _ct.get("whatsapp", ""),
        "website": env("SENDER_WEBSITE") or _co.get("website", ""),
        "company": env("SENDER_COMPANY") or _co.get("brand_display", ""),
    }

    if not os.path.exists(infile):
        print(f"ERROR: input file \"{infile}\" not found. Pass a draft list JSON (array, see the notes at the top of the script).")
        sys.exit(1)
    try:
        with open(infile, encoding="utf-8-sig") as f:
            items = json.load(f)
    except json.JSONDecodeError as e:
        print(f"ERROR: input file \"{infile}\" is not valid JSON: {e}")
        sys.exit(1)
    if isinstance(items, dict):
        items = items.get("records", items.get("items", []))

    route = _ms.resolve_sender_route()
    host, port, user, password = route["host"], route["port"], route["user"], route["password"]
    mailbox_id = route["mailbox_id"]
    if route["cap"] is not None:
        max_send = min(max_send, route["cap"])
        print(f"Hosted mailbox {mailbox_id} ({user}): {route['cap']} e-mails left in today's warm-up cap → this round's limit {max_send}")

    if not dry_run and (not host or not user or not password):
        print("ERROR: SMTP credentials missing (SMTP_HOST / SMTP_USER / SMTP_PASS, or the hosted mailbox key variable "
              f"{route.get('pass_env') or 'for the key'}). Export them first, or set DRY_RUN=1 to preview. "
              "Setup wizard: python3 scripts/mail_setup.py providers")
        sys.exit(1)

    os.makedirs(report_dir, exist_ok=True)
    _win = _sw.window_spec(profile)
    report = {"sent": [], "skipped_generic": [], "failed": [], "started_at": datetime.datetime.now().isoformat()}

    server = None
    if not dry_run:
        # Compliance: refuse clear-text delivery. Only 465 (SSL) or 587/other ports with mandatory STARTTLS.
        # Port 25 is usually clear text and is not allowed for authenticated outbound mail.
        if port == 25:
            print("ERROR: port 25 is clear-text SMTP and is not allowed for authenticated sending. Use 465 (SSL) or 587 (STARTTLS).")
            sys.exit(1)
        ctx = ssl.create_default_context()  # verifies certificate and host name by default
        if port == 465:
            server = smtplib.SMTP_SSL(host, port, context=ctx, timeout=30)
        else:
            server = smtplib.SMTP(host, port, timeout=30)
            server.ehlo()
            if not server.has_extn("starttls"):
                print("ERROR: the server does not support STARTTLS; refusing to send credentials in clear text. Use port 465 (SSL).")
                try:
                    server.quit()
                except Exception:
                    pass
                sys.exit(1)
            server.starttls(context=ctx)
            server.ehlo()
        server.login(user, password)

    count = 0
    seen_emails = set()
    report["skipped_duplicate"] = []
    try:
        for item in items:
            if count >= max_send:
                print(f"Reached the limit of {max_send} e-mails; stopping.")
                break
            email = (item.get("email") or "").strip().lower()
            if not email or "@" not in email:
                report["failed"].append({"email": email, "reason": "invalid_email"})
                continue
            if is_generic(email):
                report["skipped_generic"].append(email)
                print(f"  Skipped generic mailbox: {email}")
                continue
            if email in seen_emails:
                report["skipped_duplicate"].append(email)
                print(f"  Skipped duplicate recipient (already in this batch): {email}")
                continue
            seen_emails.add(email)
            # Recipient-local sending window (rules.local_send_window; weekdays) — outside the window skip this round, send next round
            _ok, _wi = _sw.in_window(item.get("region", ""), _win, item.get("tz", ""))
            if _ok is False and _sw.enforce_enabled():
                if dry_run:
                    item["_window_note"] = f"outside window ({_wi.get('local_time')} {_wi.get('tz')}) — real run would defer"
                else:
                    report.setdefault("deferred_window", []).append({"email": email, **_wi})
                    print(f"  Deferred (recipient local time {_wi.get('local_time')} outside window {_win}): {email}")
                    continue

            subject = item.get("subject") or f"Hello from {sender['company']}".strip()
            body = with_opt_out(build_body(item, sender, profile), profile)
            _ph = _cfg.find_placeholder_text(subject + "\n" + body)
            if _ph:
                report.setdefault("skipped_placeholder", []).append({"email": email, "placeholders": _ph})
                print(f"  Blocked (template placeholders left in subject/body: {', '.join(_ph)}): {email}")
                continue
            from_addr = user or _ct.get("email") or ""
            msg = compose(subject, body, sender["name"], from_addr, email)

            if dry_run:
                print(f"[DRY_RUN] → {email} | {subject}")
                report["sent"].append({"email": email, "brand": item.get("brand", ""), "dry_run": True,
                                       "need_tag": item.get("need_tag", "open"),
                                       "subject": subject, "body": body,
                                       "window": item.get("_window_note", "ok")})
                count += 1
                continue

            try:
                server.sendmail(user, [email], msg.as_string())
                report["sent"].append({"email": email, "brand": item.get("brand", "")})
                csv_ops(["add_sent", email, item.get("brand", ""), subject,
                         item.get("need_tag", "open")], data_dir)
                print(f"  Sent → {email}")
                count += 1
            except smtplib.SMTPRecipientsRefused:
                report["failed"].append({"email": email, "reason": "recipient_refused"})
                csv_ops(["mark_bounced", email], data_dir)
                print(f"  Rejected (probable bounce) → {email}, marked bounced")
            except Exception as e:
                report["failed"].append({"email": email, "reason": str(e)})
                print(f"  Send failed → {email}: {e}")

            time.sleep(interval)
    finally:
        if server:
            server.quit()

    if not dry_run and mailbox_id:
        _real = len([x for x in report["sent"] if not x.get("dry_run")])
        _bounced = len([x for x in report["failed"] if x.get("reason") == "recipient_refused"])
        _ms.record_usage(mailbox_id, _real, _bounced)
        if _ms.maybe_auto_pause(mailbox_id, _real, _bounced):
            print(f"[!] Hosted mailbox {mailbox_id} had too many bounces this round and was paused automatically. Check list quality, then mail_setup.py resume {mailbox_id}.")
        report["mailbox"] = mailbox_id

    report["finished_at"] = datetime.datetime.now().isoformat()
    report["summary"] = {
        "sent": len(report["sent"]),
        "skipped_generic": len(report["skipped_generic"]),
        "skipped_duplicate": len(report["skipped_duplicate"]),
        "failed": len(report["failed"]),
        "deferred_window": len(report.get("deferred_window", [])),
    }
    rpath = os.path.join(report_dir, f"batch_report_{datetime.date.today().isoformat()}.json")
    with open(rpath, "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    label = "dry run (nothing actually sent)" if dry_run else "sent"
    print(f"\nDone: {label} {len(report['sent'])}, skipped generic mailboxes {len(report['skipped_generic'])}, "
          f"skipped duplicates {len(report['skipped_duplicate'])}, failed {len(report['failed'])}. Report → {rpath}")
    if dry_run:
        print("The dry-run report includes every subject and body; check each one before removing DRY_RUN for a real send.")
    print("Run imap_scanner.py in 24-48 hours to scan for bounces.")


if __name__ == "__main__":
    main()
